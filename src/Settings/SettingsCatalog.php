<?php

declare(strict_types=1);

namespace Drupal\solo_utilities\Settings;

use Drupal\Component\Serialization\Yaml;
use Drupal\Core\Config\TypedConfigManagerInterface;
use Drupal\Core\Extension\ExtensionPathResolver;

/**
 * Describes which Solo settings exist and how they are grouped.
 *
 * Nothing here repeats a key list. The shapes are read from the schema type
 * `solo_theme_settings` (Solo's config/schema/solo.schema.yml), the default
 * values from Solo's config/install/solo.settings.yml, and the Twig variable
 * contract from config/map/solo-template-variables.yml. All three files are
 * generated by solo_utilities/scripts/settings-gen/solo-schema-gen.py from the settings map,
 * and the generator's check goes red when any of them drifts.
 *
 * Twig variable names keep their 1.x spelling (decision D1); the variable list
 * says where each one now comes from.
 *
 * @internal
 */
final class SettingsCatalog {

  /**
   * The schema type every Solo and Solo sub-theme settings object uses.
   */
  public const SCHEMA_TYPE = 'solo_theme_settings';

  /**
   * Keys core's theme_settings type owns; they are not Solo groups.
   */
  private const CORE_KEYS = ['_core', 'features', 'logo', 'favicon'];

  private const VARIABLES_FILE = 'config/map/solo-template-variables.yml';

  private const DEFAULTS_FILE = 'config/install/solo.settings.yml';

  /**
   * The compiled schema definition, once read.
   *
   * @var array<string, mixed>|null
   */
  private ?array $definition = NULL;

  /**
   * The Twig variable contract, once read.
   *
   * @var array<string, array<string, string|null>>|null
   */
  private ?array $variables = NULL;

  /**
   * Solo's install defaults, once read.
   *
   * @var array<string, mixed>|null
   */
  private ?array $defaults = NULL;

  /**
   * Constructs the catalog.
   *
   * @param \Drupal\Core\Config\TypedConfigManagerInterface $typedConfigManager
   *   The typed config manager that compiles Solo's schema type.
   * @param \Drupal\Core\Extension\ExtensionPathResolver $extensionPathResolver
   *   Finds the module and the theme on disk.
   * @param string $appRoot
   *   The Drupal root directory.
   */
  public function __construct(
    private readonly TypedConfigManagerInterface $typedConfigManager,
    private readonly ExtensionPathResolver $extensionPathResolver,
    private readonly string $appRoot,
  ) {}

  /**
   * Lists the top-level setting groups, in schema order.
   *
   * @return list<string>
   *   Group names such as `layout`, `regions` and `preloader`.
   */
  public function groups(): array {
    return array_values(array_diff(array_keys($this->mappingAt('')), self::CORE_KEYS));
  }

  /**
   * Tells whether a dotted settings path exists in the schema.
   *
   * @param string $path
   *   A path such as `regions.header.classes`.
   *
   * @return bool
   *   TRUE when the schema declares the path.
   */
  public function hasPath(string $path): bool {
    return $this->nodeAt($path) !== NULL;
  }

  /**
   * Lists the region groups (top, main, bottom, footer).
   *
   * @return list<string>
   *   Region group names.
   */
  public function regionGroups(): array {
    return array_keys($this->mappingAt('region_groups'));
  }

  /**
   * Lists the setting keys every region group carries.
   *
   * @param string $group
   *   A region group name from regionGroups().
   *
   * @return list<string>
   *   Dotted keys relative to `region_groups.<group>`.
   */
  public function regionGroupKeys(string $group): array {
    return $this->leafPaths('region_groups.' . $group);
  }

  /**
   * Lists the regions that have their own settings.
   *
   * @return list<string>
   *   Region machine names, as in solo.info.yml.
   */
  public function regions(): array {
    return array_keys($this->mappingAt('regions'));
  }

  /**
   * Lists the setting keys one region carries.
   *
   * Regions differ: some only have classes, others alignment and colors.
   *
   * @param string $region
   *   A region name from regions().
   *
   * @return list<string>
   *   Dotted keys relative to `regions.<region>`, such as `colors.text`.
   */
  public function regionKeys(string $region): array {
    return $this->leafPaths('regions.' . $region);
  }

  /**
   * Lists every stored key below a settings path.
   *
   * @param string $path
   *   A dotted path to a group, such as `preloader.logo`.
   *
   * @return list<string>
   *   Dotted keys relative to the path. A path that is itself a value gives an
   *   empty list.
   *
   * @throws \InvalidArgumentException
   *   When the schema does not declare the path.
   */
  public function leafPaths(string $path): array {
    $node = $this->nodeAt($path);
    if ($node === NULL) {
      throw new \InvalidArgumentException(sprintf('The Solo settings schema has no path "%s".', $path));
    }
    return $this->collectLeaves($node, '');
  }

  /**
   * Lists the Twig variables the page template contract provides, by group.
   *
   * @return array<string, list<string>>
   *   Variable names per contract group (misc, social, css_classes, ...).
   */
  public function templateVariableGroups(): array {
    return array_map('array_keys', $this->loadVariables());
  }

  /**
   * Maps every Twig variable to the settings path it is now read from.
   *
   * @return array<string, string|null>
   *   Variable name to dotted path. NULL means nothing is stored under that
   *   name: the code derives the value (the `count_*` family), or the region
   *   has no such setting.
   */
  public function templateVariables(): array {
    $all = [];
    foreach ($this->loadVariables() as $variables) {
      $all += $variables;
    }
    return $all;
  }

  /**
   * Lists the groups that have install defaults.
   *
   * @return list<string>
   *   Top-level group names present in Solo's install file.
   */
  public function defaultGroups(): array {
    return array_values(array_diff(array_keys($this->loadDefaults()), self::CORE_KEYS));
  }

  /**
   * Returns the shipped default values for one setting group.
   *
   * Features such as the preloader, back to top and comments are one group
   * each, so this is the feature default set.
   *
   * @param string $group
   *   A top-level group name from defaultGroups().
   *
   * @return array<string, mixed>
   *   The default values below the group.
   *
   * @throws \InvalidArgumentException
   *   When the group has no defaults.
   */
  public function defaultsFor(string $group): array {
    $defaults = $this->loadDefaults();
    if (in_array($group, self::CORE_KEYS, TRUE) || !isset($defaults[$group]) || !is_array($defaults[$group])) {
      throw new \InvalidArgumentException(sprintf('Solo has no default settings group "%s".', $group));
    }
    return $defaults[$group];
  }

  /**
   * Returns the shipped default of one setting, found by its dotted path.
   *
   * This is the single owner of a default: readers that find a key unset fall
   * back to this value, not to a literal of their own.
   *
   * @param string $path
   *   A dotted path such as `preloader.max_display_seconds`.
   *
   * @return mixed
   *   The default, or NULL when the install file declares none for the path.
   *   A default that is itself FALSE, 0, an empty string or an empty array is
   *   returned as is.
   */
  public function defaultAt(string $path): mixed {
    $node = $this->loadDefaults();
    foreach (explode('.', $path) as $segment) {
      if (!is_array($node) || !array_key_exists($segment, $node)) {
        return NULL;
      }
      $node = $node[$segment];
    }
    return $node;
  }

  /**
   * Returns the config constraints the schema declares for one setting.
   *
   * @param string $path
   *   A dotted path such as `preloader.max_display_seconds`.
   *
   * @return array<string, mixed>
   *   Constraint name to its options, such as `['Range' => ['min' => 3,
   *   'max' => 60]]`. Empty when the path is unknown or has none.
   */
  public function constraintsAt(string $path): array {
    $constraints = $this->nodeAt($path)['constraints'] ?? NULL;
    return is_array($constraints) ? $constraints : [];
  }

  /**
   * Lists every setting whose schema carries a Choice constraint.
   *
   * @return array<string, list<string>>
   *   The allowed stored values keyed by dotted path.
   */
  public function choicePaths(): array {
    $out = [];
    foreach ($this->collectLeaves($this->nodeAt('') ?? [], '') as $path) {
      $choices = $this->constraintsAt($path)['Choice']['choices'] ?? NULL;
      if (is_array($choices)) {
        $out[$path] = array_map('strval', $choices);
      }
    }
    return $out;
  }

  /**
   * Returns the schema definition node at a dotted path.
   *
   * @param string $path
   *   A dotted path; an empty string means the whole settings type.
   *
   * @return array<string, mixed>|null
   *   The node, or NULL when the schema does not declare the path.
   */
  private function nodeAt(string $path): ?array {
    $node = $this->loadDefinition();
    if ($path === '') {
      return $node;
    }
    foreach (explode('.', $path) as $segment) {
      $mapping = $node['mapping'] ?? NULL;
      if (!is_array($mapping) || !isset($mapping[$segment]) || !is_array($mapping[$segment])) {
        return NULL;
      }
      $node = $mapping[$segment];
    }
    return $node;
  }

  /**
   * Returns the child definitions of a mapping node.
   *
   * @param string $path
   *   A dotted path to a mapping.
   *
   * @return array<string, mixed>
   *   Child name to definition.
   *
   * @throws \InvalidArgumentException
   *   When the path is not a mapping the schema declares.
   */
  private function mappingAt(string $path): array {
    $mapping = $this->nodeAt($path)['mapping'] ?? NULL;
    if (!is_array($mapping)) {
      throw new \InvalidArgumentException(sprintf('The Solo settings schema has no group "%s".', $path));
    }
    return $mapping;
  }

  /**
   * Collects the stored keys below a definition node.
   *
   * @param array<string, mixed> $node
   *   A schema definition node.
   * @param string $prefix
   *   The dotted prefix of the node.
   *
   * @return list<string>
   *   The leaf paths.
   */
  private function collectLeaves(array $node, string $prefix): array {
    $leaves = [];
    $mapping = $node['mapping'] ?? NULL;
    if (!is_array($mapping)) {
      return $leaves;
    }
    foreach ($mapping as $name => $child) {
      $path = $prefix . $name;
      $below = is_array($child) ? $this->collectLeaves($child, $path . '.') : [];
      array_push($leaves, ...($below === [] ? [$path] : $below));
    }
    return $leaves;
  }

  /**
   * Reads the compiled schema type once.
   *
   * @return array<string, mixed>
   *   The merged definition, including core's theme_settings mapping.
   */
  private function loadDefinition(): array {
    if ($this->definition === NULL) {
      $definition = $this->typedConfigManager->getDefinition(self::SCHEMA_TYPE);
      $this->definition = is_array($definition) ? $definition : [];
    }
    return $this->definition;
  }

  /**
   * Reads the Twig variable contract once.
   *
   * @return array<string, array<string, string|null>>
   *   Contract group to variable name to settings path.
   */
  private function loadVariables(): array {
    if ($this->variables !== NULL) {
      return $this->variables;
    }
    $data = $this->readYaml($this->extensionPathResolver->getPath('module', 'solo_utilities') . '/' . self::VARIABLES_FILE);
    $groups = $data['groups'] ?? NULL;
    if (!is_array($groups)) {
      throw new \UnexpectedValueException('The Solo template variable file has no "groups" mapping.');
    }
    $result = [];
    foreach ($groups as $group => $variables) {
      if (!is_array($variables)) {
        throw new \UnexpectedValueException(sprintf('Template variable group "%s" is not a mapping.', $group));
      }
      foreach ($variables as $name => $path) {
        if ($path !== NULL && !is_string($path)) {
          throw new \UnexpectedValueException(sprintf('Template variable "%s" has a path that is not a string.', $name));
        }
        $result[(string) $group][(string) $name] = $path;
      }
    }
    $this->variables = $result;
    return $result;
  }

  /**
   * Reads Solo's install defaults once.
   *
   * @return array<string, mixed>
   *   The default settings tree.
   */
  private function loadDefaults(): array {
    if ($this->defaults === NULL) {
      $this->defaults = $this->readYaml($this->extensionPathResolver->getPath('theme', 'solo') . '/' . self::DEFAULTS_FILE);
    }
    return $this->defaults;
  }

  /**
   * Reads and decodes a YAML file below the Drupal root.
   *
   * @param string $relativePath
   *   The path relative to the Drupal root.
   *
   * @return array<string, mixed>
   *   The decoded data.
   *
   * @throws \RuntimeException
   *   When the file cannot be read or does not hold a mapping.
   */
  private function readYaml(string $relativePath): array {
    $file = $this->appRoot . '/' . $relativePath;
    $text = is_file($file) ? file_get_contents($file) : FALSE;
    if ($text === FALSE) {
      throw new \RuntimeException(sprintf('Cannot read %s.', $relativePath));
    }
    $data = Yaml::decode($text);
    if (!is_array($data)) {
      throw new \RuntimeException(sprintf('%s does not hold a YAML mapping.', $relativePath));
    }
    return $data;
  }

}
