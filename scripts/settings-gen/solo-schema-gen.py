def scheme_value(raw):
    """Same parse as the reader: the part after '|' if there is one, else the whole value."""
    value = unquote(raw)
    return value.split('|', 1)[1] if '|' in value else value


def map_install(install, by_old):
    tree, dropped, errors = OrderedDict(), [], []
    for key, val in install.items():
        row = by_old.get(key)
        if row is None:
            errors.append('INSTALL key not in the map: ' + key)
        elif row['action'] == 'drop':
            dropped.append(key)
        elif row['action'] == 'keep_core':
            tree[key] = val
        elif row['action'] == 'move':
            put(tree, row['new'], val)
        elif row['action'] == 'scheme_name':
            put(tree, row['new'], scheme_value(val))
        else:
            errors.append('INSTALL key %s has action %s: no default rule' % (key, row['action']))
    return ordered(tree, ('features', 'logo', 'favicon')), dropped, errors


def read_defaults_2(src=DEFAULTS_SRC):
    """Return OrderedDict path -> raw scalar from the 2.0-only defaults file (or the changed-defaults file)."""
    out = OrderedDict()
    for number, line in enumerate(open(src).read().split('\n'), 1):
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        m = re.match(r'^([a-z_0-9]+(?:\.[a-z_0-9]+)+): (.+?)\s*$', line)
        if not m:
            raise SystemExit('DEFAULTS 2.0 PARSE: unhandled line %d: %s' % (number, line))
        if m.group(1) in out:
            raise SystemExit('DEFAULTS 2.0 PARSE: duplicate key at line %d: %s' % (number, m.group(1)))
        out[m.group(1)] = m.group(2)
    return out


def defaults_2_errors(defaults, leaf_types):
    """A 2.0 default must name a schema leaf and fit that leaf's type."""
    errors = []
    for path, raw in defaults.items():
        kind = leaf_types.get(path)
        if kind is None:
            errors.append('DEFAULTS 2.0: %s is not a schema leaf' % path)
        elif kind == 'boolean' and raw not in ('true', 'false'):
            errors.append('DEFAULTS 2.0: %s is boolean, value %s' % (path, raw))
        elif kind == 'integer' and not re.match(r'^-?[0-9]+$', raw):
            errors.append('DEFAULTS 2.0: %s is integer, value %s' % (path, raw))
        elif kind == 'sequence' and raw != '[]':
            errors.append('DEFAULTS 2.0: %s is a sequence, value %s' % (path, raw))
        elif kind == 'string' and raw in ('true', 'false', '[]'):
            errors.append('DEFAULTS 2.0: %s is a string, value %s' % (path, raw))
    return errors


def constraint_scalar(value):
    """One constraint option as YAML: integers bare, text single-quoted, a list as a flow sequence."""
    if isinstance(value, list):
        return '[' + ', '.join(q(v) for v in value) + ']'
    return str(value) if isinstance(value, int) else q(value)


def read_types():
    """Return a list of (line number, path, type) from the types file."""
    out = []
    for number, line in enumerate(open(TYPES_SRC).read().split('\n'), 1):
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        m = re.match(r'^([a-z_0-9]+(?:\.[a-z_0-9]+)+): ([a-z_]+)\s*$', line)
        if not m:
            raise SystemExit('TYPES PARSE: unhandled line %d: %s' % (number, line))
        out.append((number, m.group(1), m.group(2)))
    return out


def apply_types(tree, rules):
    """Retype leaves named in the types file; return errors."""
    errors = []
    for number, path, new in rules:
        node = tree
        for part in path.split('.'):
            node = node.get(part) if isinstance(node, OrderedDict) else None
        where = 'TYPES line %d (%s)' % (number, path)
        if not isinstance(node, Leaf):
            errors.append('%s: not a schema leaf' % where)
        elif new not in TYPE_CHOICES:
            errors.append('%s: type must be one of %s' % (where, ', '.join(TYPE_CHOICES)))
        elif new == 'label' and unquote(node.rec['type']) != 'string':
            errors.append('%s: label needs a string leaf, found %s' % (where, node.rec['type']))
        elif new == 'text_format' and 'mapping_lines' not in node.rec:
            errors.append('%s: text_format needs a value/format mapping leaf' % where)
        else:
            node.rec = OrderedDict(node.rec)
            node.rec['type'] = new
            node.rec.pop('mapping_lines', None)
    return errors


def option_keys(method, source=None):
    """Return the literal keys of one SettingsOptions method as strings, or raise ValueError."""
    text = open(OPTIONS_PHP).read() if source is None else source
    m = re.search(r'public function %s\(\): array \{\n    return \[\n(.*?)\n    \];\n  \}' % re.escape(method), text, re.S)
    if not m:
        raise ValueError('method %s is not a literal return [...] list' % method)
    keys = []
    for line in m.group(1).split('\n'):
        km = re.match(r"^      (?:'([^']*)'|(-?[0-9]+)) => \$this->t\('(?:[^'\\]|\\.)*'\),$", line)
        if not km:
            raise ValueError('method %s has a line that is not a literal key: %s' % (method, line.strip()))
        keys.append(km.group(1) if km.group(1) is not None else km.group(2))
    if not keys or len(set(keys)) != len(keys):
        raise ValueError('method %s has no keys or a duplicate key' % method)
    return keys


def read_choices(source=None):
    """Return constraint rows (number, pattern, 'Choice', {choices: [...]}) and parse errors."""
    out, errors = [], []
    for number, line in enumerate(open(CHOICES_SRC).read().split('\n'), 1):
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        m = re.match(r'^([a-z_0-9*]+(?:\.[a-z_0-9*]+)+): ([A-Za-z]+)\s*$', line)
        if not m:
            raise SystemExit('CHOICES PARSE: unhandled line %d: %s' % (number, line))
        try:
            out.append((number, m.group(1), 'Choice', OrderedDict([('choices', option_keys(m.group(2), source))])))
        except ValueError as exc:
            errors.append('CHOICES line %d: %s' % (number, exc))
    return out, errors


CONSTRAINT_PATH = r'[a-z_0-9*]+(?:\.[a-z_0-9*]+)+'
CONSTRAINT_BODY = r'(Range|Length|Regex)((?: [a-z]+=\S+)+)'


def constraint_row(number, path, body):
    """Return one (line number, path, name, OrderedDict options) row from `Name option=value ...`."""
    m = re.match(r'^' + CONSTRAINT_BODY + r'\s*$', body)
    if not m:
        raise SystemExit('CONSTRAINTS PARSE: unhandled constraint at line %d: %s' % (number, body))
    opts = OrderedDict()
    for pair in m.group(2).split():
        key, raw = pair.split('=', 1)
        opts[key] = int(raw) if re.match(r'^-?[0-9]+$', raw) else raw
    return (number, path, m.group(1), opts)


def parse_constraints(text):
    """Return rows (line number, path pattern, name, OrderedDict options) from the constraints text.

    The file is valid YAML: `path: Name option=value` for one constraint, or `path:` followed by a block list of
    `  - Name option=value` items for several. A path written twice is an error (YAML would drop one of them).
    """
    out = []
    seen = {}
    current = None
    for number, line in enumerate(text.split('\n'), 1):
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        item = re.match(r'^  - (.+?)\s*$', line)
        if item:
            if current is None:
                raise SystemExit('CONSTRAINTS PARSE: list item with no path above it at line %d: %s' % (number, line))
            out.append(constraint_row(number, current, item.group(1)))
            continue
        key = re.match(r'^(' + CONSTRAINT_PATH + r'):(?: (.+?))?\s*$', line)
        if not key:
            raise SystemExit('CONSTRAINTS PARSE: unhandled line %d: %s' % (number, line))
        path, body = key.group(1), key.group(2)
        if path in seen:
            raise SystemExit('CONSTRAINTS PARSE: duplicate key %s at line %d (first at line %d); a YAML reader would drop one, '
                             'so write the constraints as a block list under one key' % (path, number, seen[path]))
        seen[path] = number
        if body is None:
            current = path
        else:
            current = None
            out.append(constraint_row(number, path, body))
    return out


def read_constraints(text=None):
    """Return the constraint rows from the constraints file (or from `text`, for the self-test)."""
    if text is None:
        text = open(CONSTRAINTS_SRC).read()
    return parse_constraints(text)


def constraint_errors(rule, leaf_types):
    """Check one constraints row and return (errors, matching leaf paths)."""
    number, pattern, name, opts = rule
    where = 'CONSTRAINTS line %d (%s %s)' % (number, pattern, name)
    errors = []
    regex = re.compile('^' + pattern.replace('.', r'\.').replace('*', '[^.]+') + '$')
    matched = [path for path in leaf_types if regex.match(path)]
    if not matched:
        errors.append('%s: matches no schema leaf' % where)
    want = {'Range': 'integer', 'Length': 'string', 'Regex': 'string', 'Choice': 'string'}[name]
    for path in matched:
        if leaf_types[path] != want:
            errors.append('%s: %s is %s, %s needs %s' % (where, path, leaf_types[path], name, want))
    allowed = {'Range': ('min', 'max'), 'Length': ('max',), 'Regex': ('pattern',), 'Choice': ('choices',)}[name]
    if not opts or any(k not in allowed for k in opts):
        errors.append('%s: options must be among %s' % (where, ', '.join(allowed)))
    for k, v in opts.items():
        if k == 'choices' and not (isinstance(v, list) and v and all(isinstance(c, str) for c in v)):
            errors.append('%s: choices must be a non-empty list of text' % where)
        if k in ('min', 'max') and not isinstance(v, int):
            errors.append('%s: %s is not an integer' % (where, k))
    if name == 'Range' and all(isinstance(opts.get(k), int) for k in ('min', 'max')) and opts['min'] > opts['max']:
        errors.append('%s: min is above max' % where)
    if name == 'Length' and isinstance(opts.get('max'), int) and opts['max'] < 1:
        errors.append('%s: max is below 1' % where)
    if name == 'Regex' and 'pattern' in opts:
        pat = opts['pattern']
        if not (len(pat) > 2 and pat[0] == pat[-1] == '/'):
            errors.append('%s: pattern needs / delimiters' % where)
    return errors, matched


def apply_constraints(tree, rules):
    """Attach every constraints row to its leaves (each Leaf gets its own copy of the record)."""
    leaves = {}

    def collect(node, prefix=''):
        for key, val in node.items():
            if isinstance(val, Leaf):
                val.rec = OrderedDict(val.rec)
                leaves[prefix + key] = val
            else:
                collect(val, prefix + key + '.')
    collect(tree)
    types = leaf_type_map(tree)
    errors = []
    for rule in rules:
        rule_errors, matched = constraint_errors(rule, types)
        errors += rule_errors
        if rule_errors:
            continue
        for path in matched:
            known = leaves[path].rec.setdefault('constraints', OrderedDict())
            if rule[2] in known:
                errors.append('CONSTRAINTS line %d: %s already has %s' % (rule[0], path, rule[2]))
            known[rule[2]] = rule[3]
    return errors


def default_fits(constraints, raw):
    """Return the reasons one raw install default breaks its constraints (empty text passes Length/Regex)."""
    problems = []
    for name, opts in constraints.items():
        if name == 'Range':
            if not re.match(r'^-?[0-9]+$', raw):
                problems.append('not an integer')
            elif int(raw) < opts['min'] or int(raw) > opts['max']:
                problems.append('%s is outside %d..%d' % (raw, opts['min'], opts['max']))
        elif name == 'Choice':
            if unquote(raw) not in opts['choices']:
                problems.append('%s is not one of %s' % (unquote(raw), ', '.join(opts['choices'])))
        else:
            text = unquote(raw)
            if text == '':
                continue
            if name == 'Length' and len(text) > opts['max']:
                problems.append('longer than %d' % opts['max'])
            if name == 'Regex' and not re.search(opts['pattern'][1:-1], text):
                problems.append('%s does not match %s' % (text, opts['pattern']))
    return problems


def constraint_default_errors(tree, install_text):
    """Every install default must satisfy the constraints of its own leaf."""
    values = flatten(parse_nested(install_text))
    out = []

    def walk(node, prefix=''):
        for key, val in node.items():
            if isinstance(val, Leaf):
                found = val.rec.get('constraints')
                if found and (prefix + key) in values:
                    out.extend('CONSTRAINTS: install default of %s %s' % (prefix + key, why) for why in default_fits(found, values[prefix + key]))
            else:
                walk(val, prefix + key + '.')
    walk(tree)
    return out


def apply_changed(tree, changed, label, required):
    """Set each deliberately changed 1.x default where the path exists; required: every path must exist."""
    errors, flat = [], flatten(tree)
    for path, raw in changed.items():
        if path not in flat:
            if required:
                errors.append('CHANGED DEFAULT: %s is not a 1.x default in %s' % (path, label))
            continue
        if flat[path] == raw:
            errors.append('CHANGED DEFAULT: %s already is %s in %s; nothing changes' % (path, raw, label))
        node = tree
        for part in path.split('.')[:-1]:
            node = node[part]
        node[path.split('.')[-1]] = raw
    return errors


def merge_defaults_2(tree, defaults):
    """Add the 2.0-only defaults to the mapped install tree (a path already there is a conflict)."""
    for path, raw in defaults.items():
        put(tree, path, raw)
    return ordered(tree, ('features', 'logo', 'favicon'))


def emit_install(tree, comment):
    lines = [HEADER + comment]

    def walk(node, indent):
        for key, val in node.items():
            if isinstance(val, OrderedDict):
                lines.append('%s%s:' % (' ' * indent, key))
                walk(val, indent + 2)
            else:
                lines.append('%s%s: %s' % (' ' * indent, key, val))
    walk(tree, 0)
    return '\n'.join(lines) + '\n'


def schema_tree(rows, recs):
    tree, groups = OrderedDict(), set()
    for row in rows:
        act = row['action']
        if act in ('drop', 'keep_core', 'fold_align_center'):
            continue
        rec = recs[row['old']]
        if act == 'fan_out_layouts':
            groups = sorted({r['new'].split('.')[1] for r in rows if r['new'] and r['new'].startswith('region_groups.') and r['action'] == 'move'})
            for g in groups:
                put(tree, 'region_groups.%s.per_content_type' % g, Leaf(rec))
        else:
            put(tree, row['new'], Leaf(rec))
    return ordered(tree, ())


def emit_schema_node(name, node, path, indent):
    pad = ' ' * indent
    if isinstance(node, Leaf):
        rec = node.rec
        lines = ['%s%s:' % (pad, name), '%s  type: %s' % (pad, rec['type']), '%s  label: %s' % (pad, rec['label'])]
        for field in ('description', 'nullable'):
            if field in rec:
                lines.append('%s  %s: %s' % (pad, field, rec[field]))
        if 'constraints' in rec:
            lines.append(pad + '  constraints:')
            for cname, opts in rec['constraints'].items():
                lines.append('%s    %s:' % (pad, cname))
                lines += ['%s      %s: %s' % (pad, k, constraint_scalar(v)) for k, v in opts.items()]
        if 'mapping_lines' in rec:
            lines.append(pad + '  mapping:')
            lines += [' ' * (indent - 4) + ln for ln in rec['mapping_lines']]
        if 'sequence' in rec:
            lines.append(pad + '  sequence:')
            lines += ['%s    %s: %s' % (pad, f, v) for f, v in rec['sequence'].items()]
        return lines
    lines = ['%s%s:' % (pad, name), pad + '  type: mapping', '%s  label: %s' % (pad, q(group_label(path))), pad + '  mapping:']
    for key, child in node.items():
        lines += emit_schema_node(key, child, path + '.' + key, indent + 4)
    return lines


def count_nodes(tree):
    leaves = groups = 0
    for val in tree.values():
        if isinstance(val, Leaf):
            leaves += 1
        else:
            groups += 1
            l, g = count_nodes(val)
            leaves, groups = leaves + l, groups + g
    return leaves, groups


