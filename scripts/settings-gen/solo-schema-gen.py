def q(value):
    return "'%s'" % str(value).replace("'", "''")


def unquote(raw):
    raw = raw.strip()
    if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in '\'"':
        return raw[1:-1]
    return raw


def humanize(segment):
    text = segment.replace('_', ' ')
    return text[:1].upper() + text[1:]


def group_label(path):
    parts = path.split('.')
    name, parent = humanize(parts[-1]), parts[-2] if len(parts) > 1 else ''
    return {'regions': name + ' region', 'region_groups': name + ' region group', 'menus': name + ' menu'}.get(parent, name)


