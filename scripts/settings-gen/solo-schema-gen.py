def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else '--check'
    src, files = cm.load(), cm.tree()
    if mode == '--self-test':
        bad = self_test(src, files)
        print('self-test: %s' % ('FAILED ' + str(bad) if bad else 'all seeds red'))
        return 1 if bad else 0
    texts, stats, errors = generate(src, files)
    errors += cm.audit(files)
    if mode == '--write':
        if errors:
            print('\n'.join(errors))
            print('NOT WRITTEN: %d red' % len(errors))
            return 1
        for name, path in FILES.items():
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w') as f:
                f.write(texts[name])
    else:
        errors += compare(texts)
    for key, val in stats.items():
        print('%s: %s' % (key, val))
    print('\n'.join(errors) if errors else 'GREEN')
    return 1 if errors else 0


