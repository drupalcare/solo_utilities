def parse_schema(text):
    """Return OrderedDict key -> {type, label, description?, nullable?, sequence?} with raw scalars."""
    recs, cur, in_seq, in_map, skip, last = OrderedDict(), None, False, False, False, None
    for number, line in enumerate(text.split('\n'), 1):
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        indent = len(line) - len(line.lstrip(' '))
        body = line.strip()
        if indent <= 2:
            continue
        m = re.match(r'^([A-Za-z_0-9]+):\s*$', body)
        if indent == 4 and m:
            cur, in_seq, in_map, skip, last = m.group(1), False, False, m.group(1) in CORE_KEYS, None
            recs[cur] = OrderedDict()
            continue
        if skip:
            continue
        m = re.match(r'^(type|label|description|nullable):\s*(.+?)\s*$', body)
        if indent == 6 and m:
            value = m.group(2)
            if m.group(1) == 'label':
                value = "'%s'" % LABEL_FIXES.get(value.strip("'"), value.strip("'")) if value.startswith("'") else LABEL_FIXES.get(value, value)
            recs[cur][m.group(1)] = value
            in_seq, last = False, m.group(1)
            continue
        if indent == 6 and body == 'sequence:':
            recs[cur]['sequence'] = OrderedDict()
            in_seq = True
            continue
        if indent == 6 and body == 'mapping:':
            # A stored array with its own children (formatted text): carried over verbatim.
            recs[cur]['mapping_lines'] = []
            in_seq, in_map = False, True
            continue
        if indent == 8 and last and not in_seq and not in_map and not re.match(r'^[A-Za-z_]+:', body):
            # Folded plain scalar: the continuation joins with one space.
            recs[cur][last] += ' ' + body
            continue
        if indent >= 8 and in_map:
            recs[cur]['mapping_lines'].append(line)
            continue
        m = re.match(r'^(type|label):\s*(.+?)\s*$', body)
        if indent == 8 and in_seq and m:
            recs[cur]['sequence'][m.group(1)] = m.group(2)
            continue
        raise SystemExit('SCHEMA PARSE: unhandled line %d: %s' % (number, line))
    return recs


def parse_nested(text):
    """Parse 'key: raw' YAML with 2-space nesting into OrderedDict of raw strings."""
    root, stack = OrderedDict(), []
    for number, line in enumerate(text.split('\n'), 1):
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        m = re.match(r'^( *)([A-Za-z0-9_]+):(?: (.*))?$', line)
        if not m or len(m.group(1)) % 2:
            raise SystemExit('YAML PARSE: unhandled line %d: %s' % (number, line))
        depth = len(m.group(1)) // 2
        del stack[depth:]
        node = stack[-1] if stack else root
        if not isinstance(node, OrderedDict) or (depth > len(stack)):
            raise SystemExit('YAML PARSE: bad nesting at line %d: %s' % (number, line))
        key, raw = m.group(2), m.group(3)
        if key in node:
            raise SystemExit('YAML PARSE: duplicate key at line %d: %s' % (number, key))
        if raw is None or raw.strip() == '':
            node[key] = OrderedDict()
            stack.append(node[key])
        else:
            node[key] = raw.rstrip()
    return root


def flatten(tree, prefix=''):
    out = OrderedDict()
    for key, val in tree.items():
        path = prefix + key
        if isinstance(val, OrderedDict):
            out.update(flatten(val, path + '.'))
        else:
            out[path] = val
    return out


def put(tree, path, value):
    parts = path.split('.')
    node = tree
    for part in parts[:-1]:
        node = node.setdefault(part, OrderedDict())
        if not isinstance(node, OrderedDict):
            raise SystemExit('TREE CONFLICT: %s passes through a value' % path)
    if parts[-1] in node:
        raise SystemExit('TREE CONFLICT: %s set twice' % path)
    node[parts[-1]] = value


def ordered(tree, core_first):
    order = list(core_first) + TOP_ORDER
    extra = [k for k in tree if k not in order]
    if extra:
        raise SystemExit('UNKNOWN TOP LEVEL GROUP: ' + ', '.join(extra))
    return OrderedDict((k, tree[k]) for k in order if k in tree)


